# The browser has already sent the file to /rails/active_storage/direct_uploads,
# so params[:signed_id] is what that step returned. File contents never pass
# through this action.
class ItemsController < ApplicationController
  before_action :require_channel!

  def create
    item = params[:signed_id].present? ? build_file_item : build_text_item

    if item.nil?
      render json: { error: "Nothing to save" }, status: :unprocessable_content
    elsif item.save
      head :created
    else
      render json: { error: item.errors.full_messages.to_sentence }, status: :unprocessable_content
    end
  rescue ActiveSupport::MessageVerifier::InvalidSignature, ActiveRecord::RecordNotFound
    render json: { error: "Invalid upload token" }, status: :unprocessable_content
  end

  def destroy
    # Invariant 3: start from current_channel, not Item.find
    item = current_channel.items.find_by(id: params[:id])
    return head :not_found unless item

    item.destroy
    head :no_content
  end

  # Invariant 1: always attachment + application/octet-stream + nosniff.
  # The content type declared at upload time is attacker-controlled; ignore it.
  #
  # send_file rather than send_data: send_data reads the whole file into memory
  # and files here are routinely gigabytes. send_file streams through Rack's
  # FileBody. x_sendfile_header is deliberately left off -- otherwise Thruster
  # serves the file directly and those three headers are no longer ours to set.
  def download
    item = current_channel.items.alive.find_by(id: params[:id], kind: "file")
    return head :not_found unless item&.file&.attached?

    blob = item.file.blob
    response.headers["X-Content-Type-Options"] = "nosniff"

    send_file disk_path_for(blob),
              filename: blob.filename.sanitized,
              type: "application/octet-stream",
              disposition: "attachment"
  end

  private

  # blob.key is a random token generated by Rails, not user input. The filename
  # (which may contain ../) plays no part in building the on-disk path.
  def disk_path_for(blob)
    ActiveStorage::Blob.service.path_for(blob.key)
  end

  def build_text_item
    body = params[:body].to_s
    return nil if body.strip.empty?

    current_channel.items.new(kind: "text", body: body, expires_at: Item.default_expires_at)
  end

  def build_file_item
    item = current_channel.items.new(kind: "file", expires_at: Item.default_expires_at)
    item.file.attach(params[:signed_id])
    item
  end
end

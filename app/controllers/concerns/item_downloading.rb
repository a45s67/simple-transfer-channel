# Invariant 1 lives here, and only here. Two controllers serve files -- the
# browser's items#download and the curl API's api/items#show -- and this concern
# is what keeps them from drifting apart.
#
# Always attachment + application/octet-stream + nosniff. The content type
# declared at upload time is attacker-controlled; ignore it.
#
# send_file rather than send_data: send_data reads the whole file into memory
# and files here are routinely gigabytes. send_file streams through Rack's
# FileBody. x_sendfile_header is deliberately left off -- otherwise Thruster
# serves the file directly and those three headers are no longer ours to set.
module ItemDownloading
  extend ActiveSupport::Concern

  private

  def send_item_file(item)
    blob = item.file.blob
    response.headers["X-Content-Type-Options"] = "nosniff"

    send_file disk_path_for(blob),
              filename: blob.filename.sanitized,
              type: "application/octet-stream",
              disposition: "attachment"
  end

  # blob.key is a random token generated by Rails, not user input. The filename
  # (which may contain ../) plays no part in building the on-disk path.
  def disk_path_for(blob)
    ActiveStorage::Blob.service.path_for(blob.key)
  end
end
